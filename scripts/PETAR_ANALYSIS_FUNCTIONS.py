def m_from_M(M, dist):
    """
    provide distance as an astropy quantity with units
    """
    m = M + (5*np.log10(dist.to(u.pc).value)) -  5
    return m

def B(nu, T):
    """
    compute a blackbody function for temperature T at frequency nu
    """
    h = const.h.cgs.value
    c = const.c.cgs.value
    k = const.k_B.cgs.value

    num = 2*h*nu**3 / c**2
    denom = np.exp(h*nu/(k*T)) - 1
    return num/denom


def define_photometric_bands():
    """
    returns gaia G, BP, RP, and (sdss?) z min/max frequencies with astropy units
    """
    ### from Gaia DR2 paper: https://www.aanda.org/articles/aa/full_html/2018/09/aa33462-18/aa33462-18.html
    lambda_G_min, lambda_G_max = 330*u.nm.to(u.micron), 1050*u.nm.to(u.micron)
    nu_G_min, nu_G_max = l_to_nu(lambda_G_max)*u.Hz, l_to_nu(lambda_G_min)*u.Hz


    lambda_BP_min, lambda_BP_max = 330*u.nm.to(u.micron), 680*u.nm.to(u.micron)
    nu_BP_min, nu_BP_max = l_to_nu(lambda_BP_max)*u.Hz, l_to_nu(lambda_BP_min)*u.Hz

    lambda_RP_min, lambda_RP_max = 630*u.nm.to(u.micron), 1050*u.nm.to(u.micron)
    nu_RP_min, nu_RP_max = l_to_nu(lambda_RP_max)*u.Hz, l_to_nu(lambda_RP_min)*u.Hz

    lambda_z = 900 * u.nm.to(u.micron)
    w_z = 100/2 * u.nm.to(u.micron)
    lambda_z_min, lambda_z_max = lambda_z - w_z, lambda_z + w_z
    nu_z_min, nu_z_max = l_to_nu(lambda_z_min)*u.Hz, l_to_nu(lambda_z_max)*u.Hz
    return nu_G_min, nu_G_max, nu_BP_min, nu_BP_max, nu_RP_min, nu_RP_max, nu_z_min, nu_z_max


def integrated_mag(nu_min, nu_max, T, R, d=10):
    """
    compute magnitude at a given frequency and stellar surface temperature/radius
    d=10 for absolute magnitude, otherwise compute with a distance
    """
    
    ### integrate over frequency 
    nu_range = np.linspace(nu_min, nu_max, 1000)

    # compute flux
    f_nu = np.pi * B(nu_range, T) ## specific flux! is pi times B_nu. 
    L_nu = f_nu * (4*np.pi*R**2) ## multiply by stellar surface area

    # adjust to 10 K Pc?
    f_fid = L_nu / (4*np.pi*(d*u.pc).cgs.value**2)

    ### now integrate this...
    f_filter = np.trapezoid(f_fid/nu_range, nu_range)
    f_filter /= np.trapezoid(1/nu_range, nu_range) ### suggestion that idk why works. 

    #### EVENTUALLY__ this should be integrated over a frequency range. 
    M = -2.5*np.log10(f_filter) - 48.60
   
    return M

def l_to_nu(l):
    """
    convert wavelength in microns to frequency in Hz
    """
    c = const.c.cgs.value
    nu = c*(1e+4)/l
    return nu




def get_gaia_photometry(Teff, Radius, distance):
    nus = define_photometric_bands()
    nu_G_min, nu_G_max, nu_BP_min, nu_BP_max, nu_RP_min, nu_RP_max, nu_z_min, nu_z_max = nus
    # frequencies = [nu_G.to(u.Hz).value, nu_BP.to(u.Hz).value, nu_RP.to(u.Hz).value]
    f_min = [nu_G_min.to(u.Hz).value, nu_BP_min.to(u.Hz).value, nu_RP_min.to(u.Hz).value]
    f_max = [nu_G_max.to(u.Hz).value, nu_BP_max.to(u.Hz).value, nu_RP_max.to(u.Hz).value]

    mags = []
    for nu_min, nu_max in zip(f_min, f_max):
        mag = integrated_mag(nu_min, nu_max, Teff, Radius, distance)
        mags.append(mag)
    return mags

def get_z_photometry(Teff, Radius, distance):
    nus = define_photometric_bands()
    nu_G_min, nu_G_max, nu_BP_min, nu_BP_max, nu_RP_min, nu_RP_max, nu_z_min, nu_z_max = nus
    f_min = nu_z_min.to(u.Hz).value
    f_max = nu_z_max.to(u.Hz).value
    mag = integrated_mag(f_min, f_max, Teff, Radius, distance)
    return mag

