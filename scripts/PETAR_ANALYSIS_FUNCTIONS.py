def compute_E_Lz(pos, vel, phi, core_pos, core_vel, mwp):
    """
    would be nice if everything had astropy units. 
    position, velocity, potential @ each particle location, 
    progenitor phase space position.
    """
    x, y, z = pos.T
    vx, vy, vz = vel.T

    xc, yc, zc = core_pos
    vxc, vyc, vzc = core_vel

    # particle  energy
    v2 = vx**2 + vy**2 + vz**2
    E = 0.5 * v2 + phi

    v2_core = vxc**2 + vyc**2 + vzc**2
    phi_core = mwp(gd.PhaseSpacePosition(core_pos, core_vel))
    E_core = 0.5 * v2_core + phi_core

    Lz = x * vy - y * vx # z component of r x v cross product. 
    Lz_core = xc * vyc - yc * vxc

    dE = E - E_core
    dLz = Lz - Lz_core

    return dE, dLz

def calc_P(a, Mtot):
    """
    period from semimajor axis, make the inputs astropy unit quantities
    """
    P = 2*np.pi * np.sqrt((a**3)/(const.G * Mtot))
    return P

def phase_fold(t, porb, t0=0):
    return ((t-t0)%porb)/porb

def calc_amplitude(binary,inclination=np.pi/2):
    """
    calculate the velocity amplitude
    in m/s for a petar binary object assuming some inclination
    (sin(i) = 1)
    """
    Mtot = (binary.mass * u.Msun)#.value
    M2 = min([binary.p1.mass, binary.p2.mass]) * u.Msun

    a = (binary.semi * u.pc).to(u.m)#.value
    e = binary.ecc
    P = calc_P(a, Mtot).to(u.s)

    a1 = (M2/Mtot) * a

    num = 2*np.pi*a1.value *np.sin(inclination)# nominally this would include sin(i)
    denom = P.value * np.sqrt(1-(e**2))
    K = num/denom # velocity semiamplitude - multiply by 2 for full amplitude.
    return K #2*K

def integrate_prog_orbit(init_displacement, steps=10000, dt = 1*u.Myr):
    pos0 = init_displacement[:3] * u.kpc 
    vel0 = init_displacement[3:] * u.km/u.s
    w0 = gd.PhaseSpacePosition(pos0, vel0)
    mwp = gp.BovyMWPotential2014(units=galactic)
    H = gp.Hamiltonian(mwp)
    orbit = H.integrate_orbit(w0, dt=dt, n_steps = steps)
    return orbit

def Trad_firstApo(orbit):
    r = np.sqrt(orbit.pos.x**2 + orbit.pos.y**2 + orbit.pos.z**2).to(u.kpc).value
    max_inds, max_vals = find_maxima(r)
    Trad = np.median(np.diff(max_inds))
