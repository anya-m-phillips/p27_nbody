def match_escape_times(IDs, properties, escaperdict):
    """
    a common example would be providing something like
    all_particles.id, coords['phi1'] as IDs, properties <- matched on ID, then
    escaper_dict_dedup as escaperdict. 
    which would return ID-matched (phi1, t_esc)
    """
    id_to_property = {ID:prop for ID, prop in zip(IDs, properties)} # create a mapping between ids and properties
    ids_in_dict = np.array(list(escaperdict.keys()))[1:] # escaperdict is the mapping between ids with escape times and escaper properties
    
    # reorder the properties to match the escaper dict
    reordered_properties = np.array([id_to_property[ID] for ID in ids_in_dict if ID in ids_in_dict]) # note some IDs won't have escape times due to merger-related ID disappearances. the if statement handles this case so that i can iterate through this dictionary at any time. 
    t_esc = np.array([escaperdict[ID]['t_esc'] for ID in ids_in_dict]) # perform the match! 
    
    return reordered_properties, t_esc

